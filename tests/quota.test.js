"use strict";
const assert=require('node:assert/strict');
require('../model.js');
const M=globalThis.BRModel;
assert.equal(M.VERSION,'quota-sensitivity-v2');
const u={b:'X',s:'1',f:12,p:500000,t:0};
const P=M.prep([u],M.PAR);
const base={cal:{P:P,a:[0],lam:0},caps:{X:0},bookedByBlock:{X:0},lastQ:0,queue:1,drops:0,called:0,chineseShare:.85,targets:['X-1'],ranked:['X-1-12'],sims:50,seed:9};
const closed=M.forecast(base),open=M.forecast({...base,caps:{X:1}});
assert.equal(closed.survive['X-1-12'],1);
assert.equal(closed.joint['X-1-12'],0);
assert.equal(closed.quotaOpen.X,0);
assert.equal(open.survive['X-1-12'],1);
assert.equal(open.joint['X-1-12'],1);
assert.equal(open.quotaOpen.X,1);
const state={meta:{queue:462,ethnicity:'Chinese',targetStacks:[],prefs:{}},queueLog:[],blockHistory:[],quotaSnap:{},quotaModel:{chineseCap:{X:1},scenarios:{low:.7,reference:.85,high:.95}}};
const units={blocks:[],units:[u]};
const a=M.cacheKey(units,state);
state.quotaModel.chineseCap.X=2;
assert.notEqual(M.cacheKey(units,state),a,'changing official caps must invalidate cache');
state.quotaModel.chineseCap.X=1;state.quotaModel.scenarios.high=.99;
assert.notEqual(M.cacheKey(units,state),a,'changing scenario mix must invalidate cache');
console.log('Quota scenario regression tests passed.');
